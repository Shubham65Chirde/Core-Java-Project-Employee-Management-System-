package com.model;

public class Employee {

	private int emid;
	private String name;
	private float salary;
	private long mob;
	
	public int getEmid() 
	{
		return emid;
	}
	public void setEmid(int emid) 
	{
		this.emid = emid;
	}
	
	public String getName() 
	{
		return name;
	}
	public void setName(String name) 
	{
		this.name = name;
	}
	
	public float getSalary() 
	{
		return salary;
	}
	public void setSalary(float salary) 
	{
		this.salary = salary;
	}
	
	public long getMob()
	{
		return mob;
	}
	public void setMob(long mob) 
	{
		this.mob = mob;
	}
	
	
}
